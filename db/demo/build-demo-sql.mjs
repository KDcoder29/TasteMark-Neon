// Builds db/migrations/2026-10-29-demo-account.sql from demo-seed.mjs:
//   node db/demo/build-demo-sql.mjs
// The SQL creates reset_demo(): it wipes everything the demo account owns and puts the sample
// journal back. It refuses to run for anyone but the demo account (its email is checked in Neon Auth).
import { writeFileSync } from 'node:fs'
import { SEED } from './demo-seed.mjs'

const EMAILS = ['demo.user@example.com', 'demo@example.com']   // keep in sync with DEMO_EMAILS in src/demoAccount.js
const json = JSON.stringify(SEED)
if (json.includes('$seed$')) throw new Error('seed text contains the SQL quote marker')

const sql = `-- The public demo accounts: "Demo" / "demo1234" (${EMAILS[0]}, used by "Try the demo")
-- and "test" / "test1234" (${EMAILS[1]}). Each one has its own copy of the sample journal.
-- Generated by db/demo/build-demo-sql.mjs from db/demo/demo-seed.mjs. Do not edit by hand.
-- Run in: Neon Console -> SQL Editor. Safe to run again (it replaces the function).
--
-- reset_demo() puts the sample journal back: ${SEED.places.length} places in Vadodara and Ahmedabad,
-- a Want to try list and a group with ratings, reactions and comments. The app calls it when a demo
-- visit starts and when the demo logs out, so nobody's changes stick. Only a demo account itself
-- can run it, and it only touches rows that belong to that account.

create or replace function reset_demo() returns void
language plpgsql security definer set search_path = public as $fn$
declare
  me uuid := auth.uid();
  seed jsonb := $seed$${json}$seed$::jsonb;
  p jsonb; d jsonb; w jsonb; pid uuid; gid uuid; did uuid; r text; c text;
begin
  if me is null or not exists (select 1 from neon_auth."user" u where u.id = me and lower(u.email) in (${EMAILS.map(e => `'${e}'`).join(', ')})) then
    raise exception 'reset_demo is only for the demo accounts';
  end if;

  -- 1. wipe everything the demo owns or added
  delete from groups where owner_id = me;                 -- its groups, with their places, wishes, activity
  delete from group_members where user_id = me;           -- any other group it joined
  delete from dish_comments where user_id = me;
  delete from dish_reactions where user_id = me;
  delete from dish_ratings where user_id = me;
  delete from places where user_id = me;                  -- with their dishes and bill photos
  delete from dishes where user_id = me;
  delete from wishlist where user_id = me;
  update profiles set display_name = (select u.name from neon_auth."user" u where u.id = me) where id = me;

  -- 2. the personal journal
  for p in select * from jsonb_array_elements(seed->'places') loop
    insert into places (user_id, group_id, name, city, area, categories, directions, created_at)
    values (me, null, p->>'name', p->>'city', p->>'area',
            array(select jsonb_array_elements_text(p->'categories')), p->>'directions',
            now() - make_interval(days => (p->>'ago')::int))
    returning id into pid;
    insert into dishes (user_id, place_id, name, price, rating, order_again, note, created_at)
    select me, pid, x->>'name', (x->>'price')::int, (x->>'rating')::int, x->>'again', x->>'note',
           now() - make_interval(days => (p->>'ago')::int)
    from jsonb_array_elements(p->'dishes') x;
  end loop;

  for w in select * from jsonb_array_elements(seed->'wishlist') loop
    insert into wishlist (user_id, group_id, name, city, area, categories, note)
    values (me, null, w->>'name', w->>'city', w->>'area', array(select jsonb_array_elements_text(w->'categories')), w->>'note');
  end loop;

  -- 3. a group: places, ratings, reactions, comments and its own Want to try list
  insert into groups (name, owner_id) values (seed->'group'->>'name', me) returning id into gid;
  insert into group_members (group_id, user_id, role) values (gid, me, 'owner');
  for p in select * from jsonb_array_elements(seed->'group'->'places') loop
    insert into places (user_id, group_id, name, city, area, categories, created_at)
    values (me, gid, p->>'name', p->>'city', p->>'area', array(select jsonb_array_elements_text(p->'categories')),
            now() - make_interval(days => (p->>'ago')::int))
    returning id into pid;
    for d in select * from jsonb_array_elements(p->'dishes') loop
      insert into dishes (user_id, place_id, name, price) values (me, pid, d->>'name', (d->>'price')::int) returning id into did;
      insert into dish_ratings (dish_id, user_id, rating, order_again, note)
      values (did, me, (d->>'rating')::int, d->>'again', d->>'note');
      for r in select * from jsonb_array_elements_text(coalesce(d->'reactions', '[]')) loop
        insert into dish_reactions (dish_id, user_id, emoji) values (did, me, r);
      end loop;
      for c in select * from jsonb_array_elements_text(coalesce(d->'comments', '[]')) loop
        insert into dish_comments (dish_id, user_id, body) values (did, me, c);
      end loop;
    end loop;
  end loop;
  for w in select * from jsonb_array_elements(seed->'group'->'wishlist') loop
    insert into wishlist (user_id, group_id, name, city, area, categories, note)
    values (me, gid, w->>'name', w->>'city', w->>'area', array(select jsonb_array_elements_text(w->'categories')), w->>'note');
  end loop;
end $fn$;

revoke all on function reset_demo() from public;
grant execute on function reset_demo() to authenticated;
notify pgrst, 'reload schema';
`

writeFileSync(new URL('../migrations/2026-10-29-demo-account.sql', import.meta.url), sql)
console.log(`wrote db/migrations/2026-10-29-demo-account.sql (${SEED.places.length} places, ${(sql.length / 1024).toFixed(0)} KB)`)
